// Digital World Engine - code generation. Produces a complete, runnable project from a
// specification: server, UI, schema, tests, Dockerfile, environment template and README.
// Deterministic (same spec → same files), platform independent (works in the browser build too).
import SERVER from './template/server.tpl.js';
import TESTS from './template/tests.tpl.js';
import { INDEX_HTML, APP_JS, STYLES_CSS } from './template/ui.tpl.js';

const escHtml = (s) => String(s).replace(/[&<>"']/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const safeName = (s) => String(s).replace(/[^a-zA-Z0-9]/g, '');

/** Normalizes the spec's entities into the generated app's schema (ASCII API names). */
export function appSchema(spec, version = 1) {
  const used = new Set();
  const entities = spec.entities.map((e, i) => {
    let name = safeName(e.name).replace(/^./, (c) => c.toLowerCase()) || `entity${i + 1}`;
    while (used.has(name)) name += 'X';
    used.add(name);
    const fieldNames = new Set();
    const fields = e.fields.map((f, j) => {
      let fname = safeName(f.name).replace(/^./, (c) => c.toLowerCase()) || `field${j + 1}`;
      while (fieldNames.has(fname)) fname += 'X';
      fieldNames.add(fname);
      return { name: fname, label: f.label ?? f.name, type: f.type, required: !!f.required, ...(f.options ? { options: f.options } : {}) };
    });
    return { name, label: e.label ?? name, labelHe: e.labelHe ?? null, public: !!e.public, fields };
  });
  return { title: spec.title, lang: spec.lang ?? 'en', version: `1.0.${version - 1}`, entities };
}

export function generateProject(spec, { version = 1 } = {}) {
  const schema = appSchema(spec, version);
  const he = schema.lang === 'he';
  const pkg = safeName(spec.slug ?? 'app').toLowerCase() || 'app';
  const files = {
    'package.json': JSON.stringify({ name: `jarvis-${pkg}`, version: schema.version, private: true, type: 'module', description: `${spec.title} (generated by JARVIS)`, engines: { node: '>=20' }, scripts: { start: 'node server.js', test: 'node --test' } }, null, 2) + '\n',
    'schema.json': JSON.stringify(schema, null, 2) + '\n',
    'server.js': SERVER,
    'public/index.html': INDEX_HTML.replace(/__TITLE__/g, escHtml(spec.title)).replace('__LANG__', he ? 'he' : 'en').replace('__DIR__', he ? 'rtl' : 'ltr'),
    'public/app.js': APP_JS,
    'public/styles.css': STYLES_CSS,
    'tests/api.test.js': TESTS,
    '.env.example': ['# Copy to .env (never commit real values)', 'PORT=3000', 'HOST=127.0.0.1', 'APP_TOKEN=   # required in production: admin bearer token', 'DATA_DIR=./data', ''].join('\n'),
    '.gitignore': 'node_modules/\ndata/\n.env\n',
    Dockerfile: ['FROM node:22-alpine', 'WORKDIR /app', 'COPY . .', 'ENV HOST=0.0.0.0 PORT=3000 DATA_DIR=/data', 'VOLUME /data', 'EXPOSE 3000', 'USER node', 'HEALTHCHECK CMD wget -qO- http://127.0.0.1:3000/api/health || exit 1', 'CMD ["node", "server.js"]', ''].join('\n'),
    'README.md': [
      `# ${spec.title}`, '', `Generated by the JARVIS Digital World Engine from: "${spec.request}"`, '',
      '## Run', '```bash', 'npm test          # API test suite against the real server', 'APP_TOKEN=change-me npm start   # http://127.0.0.1:3000', '```', '',
      '## Data model', ...schema.entities.map((e) => `- **${e.label}** (\`/api/${e.name}\`${e.public ? ', public create' : ''}): ${e.fields.map((f) => `${f.name}${f.required ? '*' : ''}:${f.type}`).join(', ')}`), '',
      '## Security', '- Admin endpoints require `Authorization: Bearer $APP_TOKEN`.', '- Server-side validation, body size limit, CSP and security headers; binds 127.0.0.1 unless HOST is set.', '',
      '## Assumptions', ...(spec.assumptions ?? []).map((a) => `- ${a}`), '',
    ].join('\n'),
  };
  return { files, schema };
}
