/** JSON file storage with atomic writes (write temp file, then rename). */
export class Db {
  constructor(file) {
    this.file = file;
    fs.mkdirSync(path.dirname(file), { recursive: true });
    this.data = fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {};
  }
  all(name) { return (this.data[name] ??= []); }
  get(name, id) { return this.all(name).find((r) => r.id === id) ?? null; }
  insert(name, rec) { const r = { id: crypto.randomUUID(), ...rec, createdAt: new Date().toISOString(), updatedAt: new Date().toISOString() }; this.all(name).push(r); this.save(); return r; }
  update(name, id, patch) { const r = this.get(name, id); if (!r) return null; Object.assign(r, patch, { updatedAt: new Date().toISOString() }); this.save(); return r; }
  remove(name, id) { const list = this.all(name); const i = list.findIndex((r) => r.id === id); if (i < 0) return false; list.splice(i, 1); this.save(); return true; }
  save() { const tmp = this.file + '.tmp'; fs.writeFileSync(tmp, JSON.stringify(this.data)); fs.renameSync(tmp, this.file); }
}

