// Template for the generated application's test suite (raw string: no backticks or placeholders inside).
// It starts the REAL server on a free port with a temporary data directory and exercises every
// endpoint over HTTP: health, schema, CRUD per entity, validation, auth, 404s, static UI, headers.
export default String.raw`// Generated by the JARVIS Digital World Engine. Run: npm test (node --test)
import { test, before, after } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { createApp, schema, validate } from '../server.js';

const TOKEN = 'test-token-' + Math.random().toString(36).slice(2);
let base; let app; let dir;
const call = async (method, p, body, auth = true) => {
  const headers = { 'Content-Type': 'application/json' };
  if (auth) headers.Authorization = 'Bearer ' + TOKEN;
  const r = await fetch(base + p, { method, headers, body: body ? JSON.stringify(body) : undefined });
  const text = await r.text();
  let json = null; try { json = text ? JSON.parse(text) : null; } catch {}
  return { status: r.status, body: json, text, headers: r.headers };
};

export function sample(f, i = 0) {
  switch (f.type) {
    case 'email': return 'user' + i + '@example.com';
    case 'phone': return '+972-50-555-00' + String(10 + i);
    case 'number': return 3 + i;
    case 'money': return 19.9 + i;
    case 'date': return '2026-01-1' + (i % 9);
    case 'datetime': return '2026-01-15T09:30:00.000Z';
    case 'boolean': return true;
    case 'enum': return f.options[0];
    case 'text': return 'Sample ' + f.name + ' text ' + i;
    default: return 'Sample ' + f.name + ' ' + i;
  }
}
const record = (e, i = 0) => Object.fromEntries(e.fields.map((f) => [f.name, sample(f, i)]));

before(async () => {
  dir = fs.mkdtempSync(path.join(os.tmpdir(), 'app-test-'));
  app = createApp({ dataDir: dir, token: TOKEN });
  await new Promise((r) => app.server.listen(0, '127.0.0.1', r));
  base = 'http://127.0.0.1:' + app.server.address().port;
});
after(() => { app.server.close(); fs.rmSync(dir, { recursive: true, force: true }); });

test('health and schema', async () => {
  const h = await call('GET', '/api/health', null, false);
  assert.equal(h.status, 200); assert.equal(h.body.ok, true); assert.equal(h.body.entities, schema.entities.length);
  const s = await call('GET', '/api/schema', null, false);
  assert.equal(s.status, 200); assert.equal(s.body.entities.length, schema.entities.length);
});

test('static UI is served with security headers', async () => {
  const r = await call('GET', '/', null, false);
  assert.equal(r.status, 200); assert.match(r.headers.get('content-type'), /text\/html/);
  assert.match(r.headers.get('content-security-policy'), /default-src 'self'/);
  assert.equal(r.headers.get('x-content-type-options'), 'nosniff');
  assert.equal((await call('GET', '/app.js', null, false)).status, 200);
  assert.equal((await call('GET', '/../server.js', null, false)).status, 404);
});

for (const e of schema.entities) {
  test('CRUD round-trip: ' + e.name, async () => {
    const c = await call('POST', '/api/' + e.name, record(e));
    assert.equal(c.status, 201, JSON.stringify(c.body));
    assert.ok(c.body.id && c.body.createdAt);
    const list = await call('GET', '/api/' + e.name);
    assert.equal(list.status, 200); assert.ok(list.body.items.some((r) => r.id === c.body.id));
    const one = await call('GET', '/api/' + e.name + '/' + c.body.id);
    assert.equal(one.status, 200); assert.equal(one.body.id, c.body.id);
    const first = e.fields[0];
    const u = await call('PUT', '/api/' + e.name + '/' + c.body.id, { [first.name]: sample(first, 7) });
    assert.equal(u.status, 200); assert.deepEqual(u.body[first.name], validate(e, { [first.name]: sample(first, 7) }, true).value[first.name]);
    const d = await call('DELETE', '/api/' + e.name + '/' + c.body.id);
    assert.equal(d.status, 204);
    assert.equal((await call('GET', '/api/' + e.name + '/' + c.body.id)).status, 404);
  });

  test('validation rejects bad input: ' + e.name, async () => {
    const required = e.fields.filter((f) => f.required);
    if (required.length) {
      const r = await call('POST', '/api/' + e.name, {});
      assert.equal(r.status, 400); assert.ok(r.body.errors.some((x) => x.includes(required[0].name)));
    }
    const typed = e.fields.find((f) => ['email', 'number', 'money', 'date', 'enum', 'boolean'].includes(f.type));
    if (typed) {
      const bad = { ...record(e), [typed.name]: typed.type === 'boolean' ? 'yes' : 'not-valid-value' };
      const r = await call('POST', '/api/' + e.name, bad);
      assert.equal(r.status, 400, typed.name + ' should be rejected');
    }
    assert.equal((await call('POST', '/api/' + e.name, { ...record(e), notAField: 1 })).status, 400);
  });

  test('authorization: ' + e.name, async () => {
    const list = await call('GET', '/api/' + e.name, null, false);
    assert.equal(list.status, 401);
    const create = await call('POST', '/api/' + e.name, record(e, 2), false);
    assert.equal(create.status, e.public ? 201 : 401);
  });
}

test('search filters records', async () => {
  const e = schema.entities[0]; const f = e.fields.find((x) => ['string', 'text'].includes(x.type)) || e.fields[0];
  const r = await call('POST', '/api/' + e.name, { ...record(e, 3), [f.name]: f.type === 'string' || f.type === 'text' ? 'Zebra-unique-term' : sample(f, 3) });
  assert.equal(r.status, 201);
  if (f.type === 'string' || f.type === 'text') {
    const s = await call('GET', '/api/' + e.name + '?q=zebra-unique');
    assert.equal(s.body.items.length, 1);
  }
});

test('errors: unknown resource, bad JSON, method, metrics auth', async () => {
  assert.equal((await call('GET', '/api/nope')).status, 404);
  const bad = await fetch(base + '/api/' + schema.entities[0].name, { method: 'POST', headers: { Authorization: 'Bearer ' + TOKEN, 'Content-Type': 'application/json' }, body: '{bad' });
  assert.equal(bad.status, 400);
  assert.equal((await call('PATCH', '/api/' + schema.entities[0].name)).status, 405);
  assert.equal((await call('GET', '/api/metrics', null, false)).status, 401);
  const m = await call('GET', '/api/metrics');
  assert.equal(m.status, 200); assert.ok(m.body.requests > 0);
});

test('data persists to disk (atomic JSON store)', async () => {
  const e = schema.entities[0];
  const c = await call('POST', '/api/' + e.name, record(e, 4));
  const onDisk = JSON.parse(fs.readFileSync(path.join(dir, 'db.json'), 'utf8'));
  assert.ok(onDisk[e.name].some((r) => r.id === c.body.id));
});
`;
