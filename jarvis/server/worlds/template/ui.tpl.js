export const APP_JS = String.raw`// Generated UI: navigation per entity, search, create/edit with validation, delete, error states.
const $ = (s) => document.querySelector(s);
const el = (tag, props = {}, ...kids) => { const n = document.createElement(tag); Object.assign(n, props); for (const k of kids) n.append(k); return n; };
let schema; let current; let editing = null;
const he = () => schema && schema.lang === 'he';
const T = (en, h) => (he() ? h : en);
const label = (e) => (he() && e.labelHe) || e.label || e.name;
const token = () => { try { return localStorage.getItem('app.token') || ''; } catch { return ''; } };

async function api(path, opts = {}) {
  const headers = { 'Content-Type': 'application/json' };
  if (token()) headers.Authorization = 'Bearer ' + token();
  const r = await fetch(path, { ...opts, headers, body: opts.body ? JSON.stringify(opts.body) : undefined });
  const data = r.status === 204 ? null : await r.json().catch(() => null);
  if (!r.ok) throw Object.assign(new Error((data && (data.errors || []).join('; ')) || (data && data.error) || ('HTTP ' + r.status)), { status: r.status });
  return data;
}

function inputFor(f, value) {
  const id = 'f_' + f.name;
  let input;
  if (f.type === 'text') input = el('textarea', { id, rows: 3 });
  else if (f.type === 'enum') { input = el('select', { id }); input.append(el('option', { value: '', textContent: '—' })); for (const o of f.options || []) input.append(el('option', { value: o, textContent: o })); }
  else if (f.type === 'boolean') input = el('input', { id, type: 'checkbox' });
  else input = el('input', { id, type: { email: 'email', phone: 'tel', number: 'number', money: 'number', date: 'date', datetime: 'datetime-local' }[f.type] || 'text' });
  if (f.type === 'money') input.step = '0.01';
  if (f.required) input.required = true;
  if (value !== undefined && value !== null) { if (f.type === 'boolean') input.checked = !!value; else if (f.type === 'datetime') input.value = String(value).slice(0, 16); else input.value = value; }
  return el('label', { className: 'field' }, el('span', { textContent: (f.label || f.name) + (f.required ? ' *' : '') }), input);
}

function readForm(e) {
  const out = {};
  for (const f of e.fields) {
    const n = document.getElementById('f_' + f.name);
    if (f.type === 'boolean') out[f.name] = n.checked;
    else if (n.value === '') continue;
    else if (f.type === 'number' || f.type === 'money') out[f.name] = Number(n.value);
    else if (f.type === 'datetime') out[f.name] = new Date(n.value).toISOString();
    else out[f.name] = n.value;
  }
  return out;
}

function renderForm(rec = null) {
  editing = rec;
  $('#formTitle').textContent = rec ? T('Edit', 'עריכה') + ' · ' + label(current) : T('New', 'חדש') + ' · ' + label(current);
  const form = $('#form'); form.replaceChildren();
  for (const f of current.fields) form.append(inputFor(f, rec ? rec[f.name] : undefined));
  const actions = el('div', { className: 'actions' }, el('button', { type: 'submit', textContent: rec ? T('Save', 'שמירה') : T('Create', 'יצירה') }));
  if (rec) actions.append(el('button', { type: 'button', className: 'ghost', textContent: T('Cancel', 'ביטול'), onclick: () => renderForm() }));
  form.append(actions);
  $('#formMsg').textContent = '';
}

async function renderList() {
  $('#listTitle').textContent = label(current);
  const table = $('#table'); table.replaceChildren(); $('#listMsg').textContent = '';
  let data;
  try { data = await api('/api/' + current.name + '?q=' + encodeURIComponent($('#q').value)); }
  catch (e) { $('#listMsg').textContent = e.status === 401 ? T('Enter the admin token to view records.', 'הזינו את אסימון המנהל כדי לראות רשומות.') : e.message; $('#listMsg').className = 'err'; return; }
  const cols = current.fields.slice(0, 5);
  table.append(el('tr', {}, ...cols.map((f) => el('th', { textContent: f.label || f.name })), el('th')));
  for (const r of data.items) {
    const tr = el('tr', {}, ...cols.map((f) => el('td', { textContent: r[f.name] === true ? '✓' : r[f.name] === false ? '' : String(r[f.name] ?? '') })));
    tr.append(el('td', { className: 'rowactions' },
      el('button', { type: 'button', className: 'ghost', textContent: '✎', title: T('Edit', 'עריכה'), onclick: () => renderForm(r) }),
      el('button', { type: 'button', className: 'danger', textContent: '✕', title: T('Delete', 'מחיקה'), onclick: async () => { if (!confirm(T('Delete this record?', 'למחוק את הרשומה?'))) return; try { await api('/api/' + current.name + '/' + r.id, { method: 'DELETE' }); renderList(); } catch (e) { $('#listMsg').textContent = e.message; } } })));
    table.append(tr);
  }
  if (!data.items.length) $('#listMsg').textContent = T('No records yet.', 'אין רשומות עדיין.');
  $('#listMsg').className = '';
}

function select(e) {
  current = e;
  for (const b of document.querySelectorAll('#nav button')) b.classList.toggle('on', b.dataset.name === e.name);
  renderForm(); renderList();
}

async function boot() {
  schema = await api('/api/schema');
  document.title = schema.title; $('#title').textContent = schema.title;
  $('#token').value = token();
  $('#saveToken').onclick = () => { try { localStorage.setItem('app.token', $('#token').value); } catch {} renderList(); };
  const nav = $('#nav');
  for (const e of schema.entities) { const b = el('button', { type: 'button', textContent: label(e), onclick: () => select(e) }); b.dataset.name = e.name; nav.append(b); }
  $('#form').onsubmit = async (ev) => {
    ev.preventDefault();
    const form = $('#form');
    if (!form.checkValidity()) { form.reportValidity(); return; }
    try {
      if (editing) await api('/api/' + current.name + '/' + editing.id, { method: 'PUT', body: readForm(current) });
      else await api('/api/' + current.name, { method: 'POST', body: readForm(current) });
      $('#formMsg').textContent = T('Saved.', 'נשמר.'); $('#formMsg').className = 'ok';
      renderForm(); renderList();
    } catch (e) { $('#formMsg').textContent = e.message; $('#formMsg').className = 'err'; }
  };
  let t; $('#q').oninput = () => { clearTimeout(t); t = setTimeout(renderList, 250); };
  select(schema.entities[0]);
  api('/api/health').then((h) => { $('#health').textContent = 'v' + h.version + ' · ' + T('healthy', 'תקין'); }).catch(() => { $('#health').textContent = T('server unreachable', 'השרת לא זמין'); });
}
boot().catch((e) => { document.body.prepend(el('p', { className: 'err', textContent: 'Failed to start: ' + e.message })); });
`;

